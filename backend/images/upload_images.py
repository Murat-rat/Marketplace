"""Upload catalog images to the private S3 bucket and write the SQL that links them.

One image per CATEGORY: name each file after a category, e.g.

    backend/images/incoming/Phones.jpg      -> every product in "Phones"
    backend/images/incoming/Laptops.png     -> every product in "Laptops"
    backend/images/incoming/Home.webp       -> every product in "Home" and its subcategories
                                               that do not have an image yet

Usage (project root, Learner Lab credentials in ~/.aws/credentials):

    .venv\\Scripts\\python backend\\images\\upload_images.py --check          # validate only, no AWS
    .venv\\Scripts\\python backend\\images\\upload_images.py --create-bucket  # first time
    .venv\\Scripts\\python backend\\images\\upload_images.py                  # later runs

Then run the generated backend/sql/local/product_images_seed.sql on RDS #1 as master.

Security:
* The bucket is created PRIVATE (Block Public Access on, owner-enforced objects,
  encryption at rest, HTTPS-only policy). Images are only reachable through the
  short-lived pre-signed links the catalog Lambda hands out.
* Files are checked by content (magic bytes), not only by extension; max 5 MB
  (the desktop app refuses bigger images anyway).
* S3 keys are random (uuid4), never the original file name.
* Category names in the generated SQL are restricted to letters, digits and
  spaces and quoted, so a file name cannot inject SQL.
"""

import argparse
import json
import re
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INCOMING = ROOT / "backend" / "images" / "incoming"
SQL_OUT = ROOT / "backend" / "sql" / "local" / "product_images_seed.sql"
DEPLOY_ENV = ROOT / "backend" / "deploy.env"

MAX_BYTES = 5 * 1024 * 1024
KEY_PREFIX = "catalog"
_NAME_RE = re.compile(r"^[A-Za-z0-9 ]{1,50}$")

# extension -> (content type, test on the first bytes of the file)
FORMATS = {
    ".jpg": ("image/jpeg", lambda b: b[:3] == b"\xff\xd8\xff"),
    ".jpeg": ("image/jpeg", lambda b: b[:3] == b"\xff\xd8\xff"),
    ".png": ("image/png", lambda b: b[:8] == b"\x89PNG\r\n\x1a\n"),
    ".webp": ("image/webp", lambda b: b[:4] == b"RIFF" and b[8:12] == b"WEBP"),
}


class ImageError(ValueError):
    pass


def category_from_filename(path: Path) -> str:
    """'Phones.jpg' -> 'Phones'; '_' and '-' count as spaces."""
    name = re.sub(r"[_\-]+", " ", path.stem).strip()
    name = re.sub(r"\s+", " ", name)
    if not _NAME_RE.fullmatch(name):
        raise ImageError(f"{path.name}: name it after a category using only letters, digits and spaces")
    return name


def check_image(path: Path) -> str:
    """Return the content type, or raise ImageError."""
    fmt = FORMATS.get(path.suffix.lower())
    if fmt is None:
        raise ImageError(f"{path.name}: only .jpg, .jpeg, .png and .webp are accepted")
    size = path.stat().st_size
    if size == 0 or size > MAX_BYTES:
        raise ImageError(f"{path.name}: must be between 1 byte and 5 MB (it is {size / 1048576:.1f} MB)")
    content_type, looks_right = fmt
    with path.open("rb") as f:
        head = f.read(16)
    if not looks_right(head):
        raise ImageError(f"{path.name}: the content is not really a {path.suffix.lower()} image")
    return content_type


def make_key(category: str, path: Path) -> str:
    slug = category.lower().replace(" ", "-")
    ext = ".jpg" if path.suffix.lower() == ".jpeg" else path.suffix.lower()
    return f"{KEY_PREFIX}/{slug}/{uuid.uuid4().hex}{ext}"


def _sql_str(value: str) -> str:
    # Values are already limited to [A-Za-z0-9 ./-]; quoting is a second safety net.
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def build_sql(entries: list[tuple[str, str]]) -> str:
    """entries: (category name, s3 key). Products that already have an image are skipped,
    so the script can be run again after new products are added."""
    lines = [
        "-- Generated by backend/images/upload_images.py. Run on RDS #1 as master.",
        "-- Gives every product WITHOUT an image the picture of its category",
        "-- (or of its parent category). Safe to run again, e.g. after adding products.",
        "",
        "USE marketplace_core;",
        "",
        "START TRANSACTION;",
    ]
    # Pass 1: products whose own category has an image (e.g. Kitchen.jpg).
    # Pass 2: the rest get their parent category's image (e.g. Home.jpg),
    # so a more specific picture always wins.
    for match, label in (("c.name", "own category"), ("parent.name", "parent category")):
        for category, key in entries:
            lines += [
                "",
                f"-- {category} ({label})",
                "INSERT INTO product_images (product_id, url, is_primary, sort_order)",
                f"SELECT p.id, {_sql_str(key)}, TRUE, 0",
                "  FROM products p",
                "  JOIN categories c           ON c.id = p.category_id",
                "  LEFT JOIN categories parent ON parent.id = c.parent_category_id",
                f" WHERE {match} = {_sql_str(category)}",
                "   AND NOT EXISTS (SELECT 1 FROM product_images pi WHERE pi.product_id = p.id);",
            ]
    lines += [
        "",
        "COMMIT;",
        "",
        "SELECT COUNT(DISTINCT product_id) AS products_with_image,",
        "       (SELECT COUNT(*) FROM products) AS total_products",
        "  FROM product_images;",
        "",
        "-- To undo (remove only these category images):",
        f"--   DELETE FROM product_images WHERE url LIKE '{KEY_PREFIX}/%';",
        "",
    ]
    return "\n".join(lines)


def collect(folder: Path) -> list[tuple[Path, str, str]]:
    """(file, category, content type) for every image in the folder.
    Raises ImageError listing every problem at once."""
    files = sorted(p for p in folder.iterdir() if p.is_file() and not p.name.startswith("."))
    if not files:
        raise ImageError(f"No images found in {folder}")
    result, problems, seen = [], [], {}
    for path in files:
        try:
            category = category_from_filename(path)
            content_type = check_image(path)
        except ImageError as err:
            problems.append(str(err))
            continue
        if category.lower() in seen:
            problems.append(f"{path.name}: {seen[category.lower()]} is already the image for '{category}'")
            continue
        seen[category.lower()] = path.name
        result.append((path, category, content_type))
    if problems:
        raise ImageError("\n".join(problems))
    return result


def read_bucket_name() -> str:
    if DEPLOY_ENV.exists():
        for line in DEPLOY_ENV.read_text(encoding="utf-8").splitlines():
            m = re.match(r'\s*IMAGES_BUCKET\s*=\s*"?([^"#\s]+)"?', line)
            if m:
                return m.group(1)
    raise ImageError("Add IMAGES_BUCKET=<bucket name> to backend/deploy.env first")


def create_private_bucket(s3, bucket: str, region: str) -> None:
    from botocore.exceptions import ClientError
    try:
        s3.head_bucket(Bucket=bucket)
        print(f"bucket  {bucket}: already exists")
    except ClientError:
        args = {"Bucket": bucket}
        if region != "us-east-1":
            args["CreateBucketConfiguration"] = {"LocationConstraint": region}
        s3.create_bucket(**args)
        print(f"bucket  {bucket}: created")
    s3.put_public_access_block(Bucket=bucket, PublicAccessBlockConfiguration={
        "BlockPublicAcls": True, "IgnorePublicAcls": True,
        "BlockPublicPolicy": True, "RestrictPublicBuckets": True})
    s3.put_bucket_ownership_controls(Bucket=bucket, OwnershipControls={
        "Rules": [{"ObjectOwnership": "BucketOwnerEnforced"}]})
    s3.put_bucket_encryption(Bucket=bucket, ServerSideEncryptionConfiguration={
        "Rules": [{"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}}]})
    s3.put_bucket_policy(Bucket=bucket, Policy=json.dumps({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "HttpsOnly", "Effect": "Deny", "Principal": "*", "Action": "s3:*",
            "Resource": [f"arn:aws:s3:::{bucket}", f"arn:aws:s3:::{bucket}/*"],
            "Condition": {"Bool": {"aws:SecureTransport": "false"}},
        }],
    }))
    print("bucket  private: public access blocked, encrypted, HTTPS only")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only validate the images (no AWS)")
    parser.add_argument("--create-bucket", action="store_true", help="create/secure the bucket first")
    args = parser.parse_args()

    INCOMING.mkdir(parents=True, exist_ok=True)
    try:
        images = collect(INCOMING)
    except ImageError as err:
        print(err, file=sys.stderr)
        return 1
    for path, category, content_type in images:
        print(f"ok      {path.name:<30} -> category '{category}' ({content_type})")
    if args.check:
        return 0

    import boto3
    try:
        bucket = read_bucket_name()
    except ImageError as err:
        print(err, file=sys.stderr)
        return 1
    session = boto3.session.Session()
    region = session.region_name or "us-east-1"
    s3 = session.client("s3", region_name=region)
    if args.create_bucket:
        create_private_bucket(s3, bucket, region)

    entries = []
    for path, category, content_type in images:
        key = make_key(category, path)
        s3.upload_file(str(path), bucket, key, ExtraArgs={
            "ContentType": content_type, "CacheControl": "private, max-age=86400"})
        print(f"upload  {path.name:<30} -> s3://{bucket}/{key}")
        entries.append((category, key))

    SQL_OUT.parent.mkdir(parents=True, exist_ok=True)
    SQL_OUT.write_text(build_sql(entries), encoding="utf-8")
    print(f"\nNow run {SQL_OUT.relative_to(ROOT)} on RDS #1 as master.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
